import type { Question } from '@/types'

/**
 * 左右(⿰)構造の漢字だけを、へん(左)とつくり(右)の2枠で組ませるための表。
 *
 * KRADFILE は部品を持つが「どこに置くか」は持たない(化 と 貝 が 貨 のように
 * 上下に並ぶのか、亻 と 立 が 位 のように左右に並ぶのかは分からない)。
 * そのため、左右に割れる字と、その左側の部品だけをここで手で持つ。
 * 右側は残りの部品なので表には持たない。
 *
 * 収録は「左+右の2部品がそのまま字形になる」左右字に絞る。
 * (組み上がりが実際の漢字に見えないと、部品を当てはめる意味が薄れるため。
 *  例: 移 は 禾+多 だが KRADFILE では 禾+夕 になり字形と合わないので入れない)
 */
const LEFT_PART_OF: Record<string, string> = {
  // さんずい
  泣: '氵', 漁: '氵', 済: '氵', 酒: '氵', 清: '氵', 波: '氵', 洋: '氵', 浴: '氵',
  // にんべん
  位: '亻', 価: '亻', 件: '亻', 仕: '亻', 他: '亻', 代: '亻', 信: '亻', 付: '亻', 仏: '亻', 俳: '亻',
  // いとへん
  級: '糸', 純: '糸', 絶: '糸', 紅: '糸',
  // ごんべん
  訓: '言', 設: '言', 討: '言', 訪: '言',
  // かねへん
  銀: '金', 鋼: '金', 針: '金',
  // きへん
  机: '木', 枝: '木', 相: '木', 根: '木', 枚: '木',
  // のぎへん
  私: '禾', 利: '禾', 和: '禾',
  // てへん
  技: '扌', 折: '扌', 投: '扌', 推: '扌', 批: '扌',
  // りっしんべん
  情: '忄', 性: '忄',
  // おうへん・いしへん・ひへん・つきへん・うしへん・けものへん・こざとへん・おんなへん
  現: '王', 破: '石', 畑: '火', 肥: '月', 物: '牛', 牧: '牛', 独: '犭', 限: '阝', 防: '阝', 好: '女',
  // 左がへんではない左右字(左側の部品を明示する)
  加: '力', 順: '川', 則: '貝', 列: '歹', 刊: '干', 敗: '貝', 放: '方', 短: '矢', 岐: '山', 眼: '目',
  帳: '巾', 張: '弓', 律: '彳', 役: '彳',
}

/** へん(左)とつくり(右)。組み立ての正解の並び */
export interface Assembly {
  left: string
  right: string
}

/**
 * その問題を「へん+つくり」の2枠で組ませられるなら、正解の左右を返す。
 *
 * 収録字で、部品がちょうど2つ、左側の部品が分かっていて、
 * 並べるタイルに左右の両方が含まれているときだけ成立する。
 */
export function assemblyOf(question: Question): Assembly | null {
  const left = LEFT_PART_OF[question.answer]
  if (!left) return null

  const parts = question.parts
  if (!parts || parts.length !== 2 || !parts.includes(left)) return null
  const right = parts[0] === left ? parts[1] : parts[0]

  const tiles = question.partTiles
  if (!tiles || !tiles.includes(left) || !tiles.includes(right)) return null

  return { left, right }
}
